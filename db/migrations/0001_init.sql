-- 0001_init —— 初版看板 schema（与 gate_db.py 的 SCHEMA 对齐）
-- 版本约定：脚本执行完后把 PRAGMA user_version 设为编号；迁移只向前，不删除数据。
PRAGMA journal_mode=WAL;
PRAGMA busy_timeout=3000;
PRAGMA foreign_keys=ON;

CREATE TABLE IF NOT EXISTS meta (k TEXT PRIMARY KEY, v TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS params (key TEXT PRIMARY KEY, value TEXT NOT NULL DEFAULT '');
CREATE TABLE IF NOT EXISTS verified (tag TEXT PRIMARY KEY, fact TEXT NOT NULL DEFAULT '', evidence TEXT NOT NULL DEFAULT '', at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS falsified (tag TEXT PRIMARY KEY, condition TEXT NOT NULL DEFAULT '', observed TEXT NOT NULL DEFAULT '', reopen TEXT NOT NULL DEFAULT '', why TEXT NOT NULL DEFAULT '', at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS hypotheses (tag TEXT PRIMARY KEY, idea TEXT NOT NULL DEFAULT '', falsifier TEXT NOT NULL DEFAULT '', budget TEXT NOT NULL DEFAULT '', at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS tooling (name TEXT PRIMARY KEY, how TEXT NOT NULL DEFAULT '', why TEXT NOT NULL DEFAULT '');
CREATE TABLE IF NOT EXISTS next_steps (ord INTEGER PRIMARY KEY, text TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS flags (flag TEXT PRIMARY KEY, confidence TEXT NOT NULL DEFAULT '', basis TEXT NOT NULL DEFAULT '');
CREATE TABLE IF NOT EXISTS stages (n INTEGER PRIMARY KEY, state TEXT NOT NULL CHECK (state IN ('通过','不通过','回退')), evidence TEXT NOT NULL DEFAULT '', at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS evidence (tag TEXT PRIMARY KEY, path TEXT NOT NULL DEFAULT '', rc INTEGER, excerpt TEXT NOT NULL DEFAULT '', at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS approved_budget (line TEXT PRIMARY KEY);
CREATE TABLE IF NOT EXISTS coverage (surface TEXT, method TEXT, param TEXT, state TEXT, tag TEXT, note TEXT, scope TEXT, at TEXT, PRIMARY KEY (surface, method, param));
CREATE TABLE IF NOT EXISTS angles (name TEXT PRIMARY KEY, result TEXT NOT NULL DEFAULT '', at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS outcomes (value TEXT PRIMARY KEY, kind TEXT NOT NULL DEFAULT 'result', at TEXT NOT NULL);

PRAGMA user_version = 1;
